export function characterNookFiles(base, person) {
  const profile = profiles[`${base}/${person.id}`];
  if (!profile) throw new Error(`Missing authored nook: ${base}/${person.id}`);
  return Object.fromEntries(NOOK_FIELDS.map(([key, title]) => {
    const body = profile[key];
    if (!body) throw new Error(`Missing nook field: ${base}/${person.id}/${key}`);
    return [`${key}.md`, md({ type: key === 'diary' ? 'component' : 'note', ...(key === 'diary' ? { component: 'diary', date: base === 'divergence' ? '1994-12-31' : '物語が始まる日' } : {}), title, portable: false }, body)];
  }));
}

export function nookProfilePaths(base, person) {
  return Object.keys(characterNookFiles(base, person));
}
