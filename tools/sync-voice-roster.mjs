#!/usr/bin/env node
/**
 * Snapshot worldlines-play's voice roster into this repo.
 *
 *   node tools/sync-voice-roster.mjs --from <path/to/voice-roster.json | https://…/voice-roster.json>
 *
 * The roster is published by worldlines-play (`node tools/voice-roster.ts --lib <worldlines-assets/voices> --out <dir>`)
 * from its voice library — the ONLY place reference_ids and their tags live. This repo never edits a reference_id;
 * it builds from a checked-in snapshot (`packages/shared/src/rules/voice-roster.snapshot.ts`) so the open-source build,
 * the tests and an offline machine all work without reaching play, and `check:voices` can prove every world character
 * resolves against exactly the list that ships. Refresh = re-run this, then build + check:voices.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const SNAPSHOT = path.join(REPO, 'packages', 'shared', 'src', 'rules', 'voice-roster.snapshot.ts');

/** Shape check — the same rules the play publisher guarantees; refuse anything else. */
export function validateRoster(r) {
  const problems = [];
  if (!r || r.schema !== 'worldlines.voice-roster/2') problems.push('schema is not worldlines.voice-roster/2');
  const ids = new Set();
  for (const v of r?.voices ?? []) {
    if (v.provider === 'fish' ? !/^[0-9a-f]{32}$/.test(v.id) : v.provider === 'dashscope' ? !/^[A-Za-z][A-Za-z0-9 _-]{0,63}$/.test(v.id) : true) problems.push(`bad ${v.provider} voice id ${v.id}`);
    if (!['female', 'male'].includes(v.gender)) problems.push(`${v.id}: gender`);
    if (!['child', 'young', 'middle', 'old'].includes(v.age)) problems.push(`${v.id}: age`);
    if (ids.has(v.id)) problems.push(`${v.id}: duplicate`);
    ids.add(v.id);
  }
  if (!ids.size) problems.push('no voices');
  for (const g of ['female', 'male']) for (const a of ['young', 'middle', 'old']) {
    const id = r?.fallback?.[`${g}/${a}`];
    if (!ids.has(id)) problems.push(`fallback ${g}/${a} is not a roster voice`);
  }
  for (const b of r?.banned ?? []) if (ids.has(b)) problems.push(`banned ${b} is still in voices`);
  const LANGS = ['zh', 'ja', 'en', 'ko'];
  for (const v of r?.voices ?? []) {
    const only = v.only === undefined ? [] : Array.isArray(v.only) ? v.only : [v.only];
    if ((Array.isArray(v.only) && !v.only.length) || only.some((l) => !LANGS.includes(l))) problems.push(`${v.id}: only ${JSON.stringify(v.only)}`);
  }
  // A character's voices are fixed at four, one per language; every one must be a roster voice.
  for (const [family, souls] of Object.entries(r?.assignedVoices ?? {})) for (const [soul, set] of Object.entries(souls ?? {})) {
    for (const l of LANGS) if (!ids.has(set?.[l])) problems.push(`assignedVoices ${family}/${soul}: ${l} ${set?.[l] ?? '(missing)'} is not a roster voice`);
  }
  return problems;
}

export function renderSnapshot(r) {
  return `/**
 * GENERATED by tools/sync-voice-roster.mjs from worldlines-play's voice roster — do not edit.
 * Source of truth: worldlines-play tools/voice-roster.ts ← worldlines-assets/voices/library.json.
 */
import type { VoiceRoster } from './voice-roster-cast.js';

export const VOICE_ROSTER: VoiceRoster = ${JSON.stringify(r, null, 2)};
`;
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const from = process.argv[process.argv.indexOf('--from') + 1];
  if (!process.argv.includes('--from') || !from) {
    console.error('usage: node tools/sync-voice-roster.mjs --from <voice-roster.json path or https URL>');
    process.exit(2);
  }
  const text = /^https:\/\//.test(from) ? await (await fetch(from)).text() : fs.readFileSync(from, 'utf-8');
  const roster = JSON.parse(text);
  const problems = validateRoster(roster);
  if (problems.length) {
    console.error(`refusing the roster:\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  fs.writeFileSync(SNAPSHOT, renderSnapshot(roster));
  console.log(`wrote ${path.relative(REPO, SNAPSHOT)} (${roster.voices.length} voices, generated ${roster.generatedAt})`);
}
