/**
 * Skeleton (S1) end-to-end probe — the deterministic writer path.
 *
 * Boots a REAL writer engine with a scripted provider that `write`s a
 * `type: component, component: map` card, then feeds the real event stream
 * through the real `mapEngineEvent` and asserts the `card_writing` frame.
 *
 * This is the "真链路" counterpart to apps/server/test/map-engine-event.test.mjs
 * (which unit-tests the pure mapper): here the engine actually produces the
 * tool events, so the mapping is exercised against a live run.
 *
 * Run: node tools/probe-skeleton.mjs
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';

import { writerLaunch } from '../apps/server/dist/engine/launch.js';
import { mapEngineEvent } from '../apps/server/dist/engine/event-bridge.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');
const VENDOR_CLI = path.join(REPO_ROOT, 'vendor/pi-rp/packages/coding-agent/dist/cli.js');
const TEST_WORLD = path.join(REPO_ROOT, 'templates/wuwu');

// The scripted component card (a `map`: chrome 'scroll', kind 'map').
const SKEL_PATH = 'world/probe-scroll.md';
const SKEL_CONTENT = [
  '---',
  'type: component',
  'component: map',
  'title: Probe Chart',
  '---',
  'A chart of the unseen harbour.',
  '',
].join('\n');

// The provider is a jiti-run TS module passed explicitly to the engine (same
// mechanism the other probes use); written at run time so it never lands in git.
// It MUST default-export a factory `(pi) => void` that calls `pi.registerProvider`.
const providerSource = () => `// Auto-generated by tools/probe-skeleton.mjs — do not commit.
import { createAssistantMessageEventStream } from '@earendil-works/pi-ai/compat';

const PROVIDER_ID = 'airp-skeleton-probe';
const MODEL_ID = 'deterministic';
const SKEL_PATH = ${JSON.stringify(SKEL_PATH)};
const SKEL_CONTENT = ${JSON.stringify(SKEL_CONTENT)};
let turn = 0;

function usage() {
  return { input: 10, output: 20, cacheRead: 0, cacheWrite: 0, totalTokens: 30, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } };
}

export default function skeletonProbeProvider(pi) {
  pi.registerProvider(PROVIDER_ID, {
    name: 'Skeleton probe (deterministic)',
    baseUrl: 'http://127.0.0.1:0',
    apiKey: 'probe-key',
    api: 'openai-completions',
    models: [
      {
        id: MODEL_ID,
        name: 'Deterministic skeleton model',
        reasoning: false,
        input: ['text'],
        cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
        contextWindow: 128000,
        maxTokens: 4096,
      },
    ],
    streamSimple: (model) => {
      const stream = createAssistantMessageEventStream();
      turn = (turn % 2) + 1;
      const content = turn === 1
        ? [{ type: 'toolCall', id: 'skel_call_' + turn, name: 'write', arguments: { path: SKEL_PATH, content: SKEL_CONTENT } }]
        : [{ type: 'text', text: 'done' }];
      const message = { role: 'assistant', content, api: model.api, provider: model.provider, model: model.id, usage: usage(), stopReason: turn === 1 ? 'toolUse' : 'stop', timestamp: Date.now() };
      queueMicrotask(() => {
        stream.push({ type: 'start', partial: { ...message, content: [], stopReason: 'pending' } });
        message.content.forEach((block, i) => {
          if (block.type === 'text') {
            stream.push({ type: 'text_start', contentIndex: i, partial: message });
            stream.push({ type: 'text_delta', contentIndex: i, delta: block.text, partial: message });
            stream.push({ type: 'text_end', contentIndex: i, content: block.text, partial: message });
          } else {
            stream.push({ type: 'toolcall_start', contentIndex: i, partial: message });
            stream.push({ type: 'toolcall_delta', contentIndex: i, delta: JSON.stringify(block.arguments), partial: message });
            stream.push({ type: 'toolcall_end', contentIndex: i, toolCall: block, partial: message });
          }
        });
        stream.push({ type: 'done', message });
      });
      return stream;
    },
  });
}
`;

async function main() {
  const { RpcClient } = await import(
    path.join(REPO_ROOT, 'vendor/pi-rp/packages/coding-agent/dist/index.js')
  );

  const providerTs = path.join(__dirname, 'skeleton-probe-provider.ts');
  fs.writeFileSync(providerTs, providerSource(), 'utf-8');

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'airp-skel-probe-'));
  fs.cpSync(TEST_WORLD, tmp, { recursive: true });
  fs.rmSync(path.join(tmp, '.airpworld', 'sessions'), { recursive: true, force: true });

  const spec = writerLaunch(REPO_ROOT, tmp, VENDOR_CLI);
  const client = new RpcClient({
    cliPath: spec.cliPath,
    cwd: spec.cwd,
    args: [...spec.args, '--extension', providerTs],
    env: { ...spec.env, PI_OFFLINE: '1' },
    provider: 'airp-skeleton-probe',
    model: 'deterministic',
  });

  const toolArgs = new Map();
  const frames = [];
  client.onEvent((event) => {
    for (const frame of mapEngineEvent('writer', event, toolArgs)) frames.push(frame);
  });

  try {
    await client.start();
    const state = await client.getState();
    if (state.model?.provider !== 'airp-skeleton-probe') {
      throw new Error(`deterministic provider not loaded (provider=${state.model?.provider ?? 'none'})`);
    }
    await client.prompt('sketch a chart of the harbour');
    await client.waitForIdle(30000);
  } finally {
    if (typeof client.stop === 'function') await client.stop().catch(() => {});
    fs.rmSync(providerTs, { force: true });
    fs.rmSync(tmp, { recursive: true, force: true });
  }

  const frame = frames.find((f) => f.type === 'card_writing');
  assert.ok(frame, `no card_writing frame emitted; saw: ${[...new Set(frames.map((f) => f.type))].join(', ')}`);
  assert.equal(frame.source, 'writer');
  assert.equal(frame.kind, 'map');
  assert.equal(frame.title, 'Probe Chart');
  // `world/` is the root layer, whose id is `map` (layers.ts layerOfDir).
  assert.equal(frame.layer, 'map');
  assert.equal(frame.path, undefined);
  // Ordering: card_writing (start) must precede chalk_landed (end) for the same id.
  const iWrite = frames.findIndex((f) => f.type === 'card_writing');
  const iLand = frames.findIndex((f) => f.type === 'chalk_landed' && f.toolCallId === frame.toolCallId);
  assert.ok(iWrite >= 0 && iLand > iWrite, 'register must precede land for the same toolCallId');

  console.log('✓ tool_execution_start → card_writing frame emitted by a live engine');
  console.log(`  kind=${frame.kind} title=${JSON.stringify(frame.title)} layer=${frame.layer}`);
  console.log('✓ card_writing precedes chalk_landed for the same toolCallId');
  console.log('SKELETON PROBE PASSED');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
